'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const EL = {Renderer:function(){}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/render/draw.js'),'utf8'), {window:{EL}});
const r = Object.create(EL.Renderer.prototype);
r.labelPreferences = new Map(); r.draw = () => {};
r.scene = {labels:[{id:'point:M',text:'M',hidden:true},{text:'r',cls:'dim'},{text:'r',cls:'dim'}]};
assert.equal(r.getLabelKey(r.scene.labels[0],0),'point:M');
assert.equal(r.getLabelKey(r.scene.labels[1],1),'dim:r');
assert.equal(r.getLabelKey(r.scene.labels[2],2),'dim:r:1');
assert.equal(r.isLabelVisible(r.scene.labels[0],0),false);
r.setLabelVisible('point:M',true);
assert.equal(r.isLabelVisible(r.scene.labels[0],0),true);
r.labelPreferences.set('point:M',{visible:true,dx:45,dy:-22});
r.scene.labels.reverse();
assert.equal(r.isLabelVisible(r.scene.labels[2],2),true);
r.resetLabelOffsets('point:M');
assert.equal(r.labelPreferences.get('point:M').visible,true);
assert.equal(r.labelPreferences.get('point:M').dx,undefined);
r.moveLabel('point:M', 180, -125);
const position = {...r.labelPreferences.get('point:M')}, x = position.dx + 7 + 20, y = position.dy - 18 + 10;
assert.ok(Math.hypot(x / 52, y / 42) <= 1 + 1e-12, 'drag remains near the anchored element');
assert.ok(position.dx < 180 && position.dy > -125, 'large offsets are constrained');
r.moveLabel('point:M', NaN, 1);
assert.deepEqual({...r.labelPreferences.get('point:M')}, position);
r.resetLabels();
assert.equal(r.isLabelVisible(r.scene.labels[2],2),false);
console.log('annotation identities, explicit visibility and reset behavior passed');
