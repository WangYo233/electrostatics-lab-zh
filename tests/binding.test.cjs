'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.join(__dirname, '..');
const context = vm.createContext({ window: {}, console });
for (const file of ['js/core/vec.js', 'js/core/util.js', 'js/physics/geometry.js', 'js/app/state.js', 'js/app/panels.js', 'js/app/panels2.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file });
}
const { App: A, GEO } = context.window.EL;
const plain = value => JSON.parse(JSON.stringify(value));
const shape = x => ({ type: 'cube', w: 4, l: 3, h: 3, x, y: 0, z: 0 });
A.st = { custom: [{ p: [8, 9, 10], q: -2, label: 'Q1' }, { p: [1, 2, 3], q: 4, label: 'Q2' }], hidden: { bgs: [shape(0), shape(10)] }, showSpecial: 1 };
const st = A.st, first = st.custom[0], point = GEO.build(st.hidden.bgs[0]).special[0];
assert.equal(A.bindSource(0, { bg: 0, key: point.key }), true);
assert.equal(st.custom[0], first, 'binding modifies the existing charge, not its identity');
assert.equal(st.custom.length, 2);
assert.equal(st.custom[0].q, -2);
assert.deepEqual(plain(A.resolveSources()[0].p), plain(point.p));
st.hidden.bgs[0].x = 5; st.hidden.bgs[0].w = 8;
const moved = GEO.build(st.hidden.bgs[0]).special[0].p;
assert.deepEqual(plain(A.resolveSources()[0].p), plain(moved), 'binding follows both translation and resize');
assert.equal(A.bindSource(0, null), true);
assert.deepEqual(plain(st.custom[0].p), plain(moved), 'unbind preserves current world coordinates');
st.hidden.bgs[0].x = 20;
assert.deepEqual(plain(A.resolveSources()[0].p), plain(moved), 'unbound charge stays put');
assert.equal(A.bindSource(0, { bg: 1, key: point.key }), true);
const rebound = A.resolveSources()[0].p.slice();
assert.equal(A.bindSource(1, { bg: 0, key: point.key }), true);
st.hidden.bgs[0].x = 30;
const beforeRemoval = A.resolveSources()[1].p.slice();
A.removeBackground(0);
assert.equal(st.custom[0].bind.bg, 0, 'remaining background binding is reindexed');
assert.deepEqual(plain(A.resolveSources()[0].p), plain(rebound));
assert.equal(st.custom[1].bind, null);
assert.deepEqual(plain(st.custom[1].p), plain(beforeRemoval), 'deleting a moved background does not jump the charge');
assert.equal(st.showSpecial, 0);
const saved = JSON.stringify(st.custom);
assert.equal(A.bindSource(0, { bg: 10, key: 'missing' }), false);
assert.equal(JSON.stringify(st.custom), saved, 'invalid target leaves binding and coordinates unchanged');
A.removeBackground(0);
assert.equal(st.showSpecial, -1);
assert.deepEqual(plain(st.custom[0].p), plain(rebound));
console.log('Existing-charge binding: translation, resize, rebind, unbind, deletion and invalid target passed.');
